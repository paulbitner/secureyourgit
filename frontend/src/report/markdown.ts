import { site } from '../config/site';
import { getRule } from '../scanner/registry';
import { SEVERITY_ORDER, type Finding } from '../scanner/types';
import type { GradeResult } from './grade';

const fence = (code: string) => {
  // Use a fence longer than any backtick run inside the snippet.
  const longest = Math.max(2, ...(code.match(/`+/g) ?? []).map((m) => m.length));
  const ticks = '`'.repeat(longest + 1);
  return `${ticks}yaml\n${code}\n${ticks}`;
};

/**
 * A Markdown report suitable for a PR description or ticket. Contains finding
 * metadata and fix snippets only — never the scanned workflow itself.
 */
export function reportToMarkdown(findings: readonly Finding[], grade: GradeResult, fileName?: string): string {
  const lines: string[] = [];
  lines.push(`## GitHub Actions security report${fileName ? `: \`${fileName}\`` : ''}`, '');
  lines.push(`**Grade: ${grade.grade}** (${grade.score}/100) · ${grade.total} finding${grade.total === 1 ? '' : 's'}`, '');
  lines.push('| Severity | Count |', '|---|---|');
  for (const s of SEVERITY_ORDER) lines.push(`| ${s[0]!.toUpperCase()}${s.slice(1)} | ${grade.counts[s]} |`);
  lines.push('');

  if (findings.length === 0) {
    lines.push('No issues found. ✅', '');
  }

  findings.forEach((f, i) => {
    const rule = getRule(f.ruleId);
    lines.push(`### ${i + 1}. [${f.severity.toUpperCase()}] ${f.title}`, '');
    lines.push(`- **Line:** ${f.line}`);
    lines.push(`- **Rule:** [\`${f.ruleId}\`](${site.url}/rules/${f.ruleId}/)${rule ? ` — ${rule.title}` : ''}`, '');
    lines.push(`**What's wrong:** ${f.message}`, '');
    lines.push(`**Why it matters:** ${f.why}`, '');
    if (f.fix) lines.push('**Suggested fix:**', '', fence(f.fix), '');
  });

  lines.push(`---`, `_Generated by [${site.name}](${site.url}/) — scanned locally in the browser._`, '');
  return lines.join('\n');
}
